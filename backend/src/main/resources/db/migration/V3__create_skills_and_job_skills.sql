CREATE TABLE skills (
    id UUID PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    normalized_name VARCHAR(100) NOT NULL,
    category VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_skills_normalized_name UNIQUE (normalized_name)
);

CREATE TABLE skill_aliases (
    id UUID PRIMARY KEY,
    skill_id UUID NOT NULL,
    alias VARCHAR(100) NOT NULL,
    normalized_alias VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_skill_aliases_skill FOREIGN KEY (skill_id) REFERENCES skills (id),
    CONSTRAINT uk_skill_aliases_normalized_alias UNIQUE (normalized_alias)
);

CREATE TABLE job_skills (
    id UUID PRIMARY KEY,
    job_posting_id UUID NOT NULL,
    skill_id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_job_skills_job_posting FOREIGN KEY (job_posting_id) REFERENCES job_postings (id) ON DELETE CASCADE,
    CONSTRAINT fk_job_skills_skill FOREIGN KEY (skill_id) REFERENCES skills (id),
    CONSTRAINT uk_job_skills_job_posting_skill UNIQUE (job_posting_id, skill_id)
);

CREATE INDEX idx_job_skills_skill ON job_skills (skill_id);

